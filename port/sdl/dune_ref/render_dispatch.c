static int use8;

SDL_Renderer *SDL_CreateRenderer(SDL_Window *window, int index, Uint32 flags)
{
    use8 = msdl_window_depth(window) == 8;
    return use8 ? r8_CreateRenderer(window, index, flags) : r16_CreateRenderer(window, index, flags);
}

